#!/bin/bash

# Скрипт установки зависимостей для Telegram бота

# Проверяем, что скрипт запущен из правильной директории
if [ ! -f "bot.py" ]; then
    echo "Ошибка: Не найден файл bot.py. Убедитесь, что вы запускаете скрипт из корневой директории проекта."
    exit 1
fi

# Проверяем наличие Python
if ! command -v python3 &> /dev/null; then
    echo "Ошибка: Python 3 не найден. Пожалуйста, установите Python 3."
    exit 1
fi

# Проверяем наличие pip
if ! command -v pip &> /dev/null; then
    echo "Ошибка: pip не найден. Пожалуйста, установите pip."
    exit 1
fi

# Создаем виртуальное окружение (если оно еще не создано)
if [ ! -d "venv" ]; then
    echo "Создание виртуального окружения..."
    python3 -m venv venv
    if [ $? -ne 0 ]; then
        echo "Ошибка: Не удалось создать виртуальное окружение."
        exit 1
    fi
fi

# Активируем виртуальное окружение
echo "Активация виртуального окружения..."
source venv/bin/activate

# Обновляем pip
echo "Обновление pip..."
pip install --upgrade pip

# Устанавливаем зависимости
echo "Установка зависимостей..."
pip install -r requirements.txt

# Проверяем установку зависимостей
if [ $? -ne 0 ]; then
    echo "Ошибка: Не удалось установить зависимости."
    exit 1
fi

echo "Установка завершена успешно!"

# Проверяем наличие файла .env
if [ ! -f ".env" ]; then
    echo "Предупреждение: Файл .env не найден. Пожалуйста, создайте его на основе .env.example и заполните данными."
fi

echo "Для запуска бота используйте команду:"
echo "source venv/bin/activate && python3 bot.py"